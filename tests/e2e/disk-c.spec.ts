test('the supplied Disk B save plays through the staffed ambulance rescue and reaches Disk D @journey',async({page})=>{
  test.setTimeout(300000);
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');await expect(page).toHaveTitle(/Borrowed Tomorrow/);await importSave(page,departure);
  await expect(page.getByRole('heading',{name:'Insert Disk C',exact:true})).toBeVisible();
  await page.route('**/art/infirmary.webp',route=>route.abort());
  await page.getByRole('button',{name:'Begin Disk C',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('arrival save is intact',{timeout:20000});
  const retained=(await inspect(page)).state;expect(retained.boundary).toBe(departure.boundary);expect(retained.chapter).toBe('disk-b');
  await page.unroute('**/art/infirmary.webp');
  await page.getByRole('button',{name:'Begin Disk C',exact:true}).click();await dialogue(page);
  const entered=(await inspect(page)).state;
  expect(entered.version).toBe(4);expect(entered.chapter).toBe('disk-c');expect(entered.party).toEqual(departure.party);
  for(const property of ['coins','bandages','xp','gear'] as const)expect(entered[property]).toEqual(departure[property]);
  expect(entered.flags.bOrchardChannel).toBe(true);expect(entered.flags.bWorksheetRead).toBe(true);
  expect(entered.journal).toContain('c-flour-credit');await nativeScene(page,'cinderbank');await capture(page,'disk-c-cinderbank-arrival');
  await visit(page,'c-water');await visit(page,'c-carriage');await visit(page,'c-dispatch');await visit(page,'c-workbook');
  await travel(page,'c-to-infirmary','infirmary');await nativeScene(page,'infirmary');await capture(page,'disk-c-bellwether');
  await visit(page,'c-celia');await visit(page,'c-beds');
  await travel(page,'c-to-siding','cinderbank');await approach(page,'c-couplings');await dialogue(page);await battle(page,'disk-c-supply-lanes');
  await approach(page,'c-valve');
  const choice=page.getByRole('button',{name:'Heat the north ward · travel under blankets',exact:true});
  while(!await choice.isVisible())await page.locator('.dialogue-actions button').first().click();
  await choice.click();await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect.poll(async()=>(await inspect(page)).state.flags.cWardHeat).toBe(true);
  await approach(page,'c-valve');await dialogue(page);
  await expect.poll(async()=>(await inspect(page)).mode).toBe('battle');
  expect((await inspect(page)).battle!.vents).toHaveLength(5);await battle(page,'disk-c-boiler-vents');
  await visit(page,'c-dispatch');expect((await inspect(page)).state.flags.cCrewAccepted).toBe(true);
  await approach(page,'c-carriage');
  const dispatch=page.getByRole('button',{name:'Dispatch fourteen patients to Bellwether',exact:true});
  while(!await dispatch.isVisible())await page.locator('.dialogue-actions button').first().click();
  await dispatch.click();await dialogue(page);
  await expect.poll(async()=>(await inspect(page)).state.location.map).toBe('infirmary');
  await visit(page,'c-patients');await visit(page,'c-ward');await capture(page,'disk-c-fourteen-received');
  await travel(page,'c-to-siding','cinderbank');await travel(page,'c-to-larkspur','station');
  await visit(page,'master');await visit(page,'c-tilda');await visit(page,'b-family-larkspur');
  await visit(page,'train');await expect(page.getByRole('heading',{name:'Insert Disk D',exact:true})).toBeVisible();
  const final=(await inspect(page)).state;
  expect(final.flags.cTransferred).toBe(true);expect(final.flags.cReceiptSigned).toBe(true);expect(final.flags.diskCComplete).toBe(true);
  expect(final.boundary).toBe('disk-d:signal-works');expect(final.flags.promisedHome).toBe(true);
  expect(final.flags.bOrchardChannel).toBe(true);expect(final.gear).toEqual(departure.gear);
  if(process.env.BT_QA_SAVE_OUTPUT)await writeFile(process.env.BT_QA_SAVE_OUTPUT,JSON.stringify(final,null,2));
  await capture(page,'disk-c-insert-d');
  await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Insert Disk D',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Return to the line',exact:true}).click();
  // Completed earlier chapters remain open without consuming the new boundary.
  await travel(page,'to-yard','yard');await travel(page,'to-tunnel','tunnel');await travel(page,'disk-b','rillbridge');
  await visit(page,'b-crossing');expect((await inspect(page)).state.boundary).toBe(final.boundary);
  expect(errors).toEqual([]);
});

test('the other heating choice persists on a phone, and Mend and Bandage confirm healing',async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  const state=enterDiskC(decodeSave(JSON.stringify(departure)));
  Object.assign(state.flags,{cWarmed:true,cManifestRefused:true,cRegisterRead:true,cCeliaMet:true,cBedsReserved:true,cCouplingRecovered:true});
  state.location={map:'cinderbank',x:48,y:20};state.party[0].hp=38;state.party[1].hp=42;
  await importSave(page,state);await expect.poll(async()=>(await inspect(page)).state.chapter).toBe('disk-c');
  await approach(page,'c-valve');
  const choice=page.getByRole('button',{name:'Heat the train · one crowded receiving hall',exact:true});
  while(!await choice.isVisible())await page.locator('.dialogue-actions button').first().click();
  await expect(choice).toBeInViewport();await expect(page.getByRole('button',{name:'Heat the north ward · travel under blankets',exact:true})).toBeInViewport();
  await capture(page,'disk-c-phone-heat-choice');await choice.click();
  const confront=page.getByRole('button',{name:'Confront the boiler keeper',exact:true});
  while(!await confront.isVisible())await page.locator('.dialogue-actions button').first().click();
  await expect(confront).toBeInViewport();expect((await inspect(page)).mode).toBe('world');
  await page.getByRole('button',{name:'Prepare in the yard',exact:true}).click();
  await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect.poll(async()=>(await inspect(page)).state.flags.cTrainHeat).toBe(true);
  await approach(page,'c-valve');await dialogue(page);
  await expect.poll(async()=>(await inspect(page)).mode).toBe('battle');
  const before=(await inspect(page)).battle!;expect(before.vents).toHaveLength(10);
  await page.locator('.actions').getByRole('button',{name:/^4\s+Mend$/}).click();await clickHex(page,before.units[0].hex);
  const heal=page.getByRole('button',{name:'Confirm healing',exact:true});await expect(heal).toBeInViewport();
  await expect(page.getByRole('button',{name:'Confirm attack',exact:true})).toHaveCount(0);await capture(page,'disk-c-phone-mend');await heal.click();
  await expect.poll(async()=>(await inspect(page)).battle!.units[0].hp).toBe(before.units[0].hp+18);
  const bandage=page.locator('.actions').getByRole('button',{name:/^4\s+Bandage$/});await expect(bandage).toBeEnabled({timeout:15000});
  const snapshot=(await inspect(page)).battle!,orrin=snapshot.units.find(u=>u.id==='orrin')!;
  expect(active({...snapshot,obstacles:new Set(snapshot.obstacles),water:new Set(snapshot.water),vents:new Set(snapshot.vents)})!.id).toBe('orrin');
  await bandage.click();await clickHex(page,orrin.hex);await expect(heal).toBeInViewport();
  await expect(page.getByRole('button',{name:'Confirm attack',exact:true})).toHaveCount(0);await capture(page,'disk-c-phone-bandage');await heal.click();
  await expect.poll(async()=>(await inspect(page)).battle!.bandages).toBe(snapshot.bandages-1);
  expect((await inspect(page)).battle!.units.find(u=>u.id==='orrin')!.hp).toBe(Math.min(orrin.maxHp,orrin.hp+24));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
