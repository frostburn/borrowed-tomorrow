import { expect, test } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import departure from '../fixtures/disk-c-v3.json' with {type:'json'};
import { decodeSave, enterDiskD } from '../../src/rules/state';
import { MAPS } from '../../src/content/maps';
import { battle, capture, dialogue, inspect, nativeScene } from './controls';
import { approach, importSave, travel, visit } from './navigation';

test('the supplied Disk C save collects the letter, rescues all six workers, earths the relay and reaches Disk E',async({page})=>{
  test.setTimeout(300000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const missing:string[]=[];page.on('response',r=>{if(r.url().includes('/art/')&&r.status()>=400)missing.push(r.url());});
  await page.goto('/');await expect(page).toHaveTitle(/Borrowed Tomorrow/);await importSave(page,departure);
  await expect(page.getByRole('heading',{name:'Insert Disk D',exact:true})).toBeVisible();
  await page.route('**/art/relayhall.webp',route=>route.abort());
  await page.getByRole('button',{name:'Begin Disk D',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('arrival save is intact',{timeout:20000});
  expect((await inspect(page)).state.chapter).toBe('disk-c');expect((await inspect(page)).state.boundary).toBe(departure.boundary);
  await page.unroute('**/art/relayhall.webp');
  await page.getByRole('button',{name:'Begin Disk D',exact:true}).click();await dialogue(page);
  const entered=(await inspect(page)).state;expect(entered.version).toBe(4);expect(entered.chapter).toBe('disk-d');
  for(const property of ['party','coins','bandages','xp','gear'] as const)expect(entered[property]).toEqual(departure[property]);
  for(const [flag,value] of Object.entries(departure.flags))expect(entered.flags[flag]).toBe(value);
  const exit=MAPS.northglass.objects.find(o=>o.id==='d-to-larkspur')!;
  expect(Math.abs(entered.location.x-exit.x)+Math.abs(entered.location.y-exit.y)).toBe(1);
  await nativeScene(page,'northglass');await capture(page,'disk-d-arrival');
  await approach(page,'d-petra');await expect(page.locator('.dialogue h2')).toHaveText('Petra');
  await expect(page.locator('.dialogue-portrait img')).toHaveAttribute('src',/portrait-petra\.png$/);
  await capture(page,'disk-d-petra-letter');await dialogue(page);
  expect((await inspect(page)).state.flags.dLetterRead).toBe(true);expect((await inspect(page)).state.flags.dLineHeld).toBeUndefined();
  await visit(page,'d-lamp');await approach(page,'d-tram');await dialogue(page);await battle(page,'disk-d-workers-road');
  expect((await inspect(page)).state.flags.dCrewReturned).toBe(true);
  await travel(page,'d-to-hall','relayhall');await nativeScene(page,'relayhall');await capture(page,'disk-d-relay-hall');
  await approach(page,'d-esme-hall');await expect(page.locator('.dialogue h2')).toHaveText('Esme');
  await expect(page.locator('.dialogue-portrait img')).toHaveAttribute('src',/portrait-esme\.png$/);
  await page.getByRole('button',{name:'Rest at the workbench · free',exact:true}).click();
  await visit(page,'d-circuit');await visit(page,'d-plaque');await approach(page,'d-plan');
  const plan=page.getByRole('button',{name:'Work by hand bell · keep local deliveries',exact:true});
  while(!await plan.isVisible())await page.locator('.dialogue-actions button').first().click();
  await plan.click();await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect.poll(async()=>(await inspect(page)).state.flags.dHandBell).toBe(true);
  await approach(page,'d-relay');await dialogue(page);
  await expect.poll(async()=>(await inspect(page)).mode).toBe('battle');
  const sealed=(await inspect(page)).battle!;expect(sealed.grounding?.open).toBe(false);expect(sealed.units.find(u=>u.appearance==='relay-keeper')!.sealed).toBe(true);
  await battle(page,'disk-d-paired-earths');
  await visit(page,'d-recorder');await travel(page,'d-to-yard','northglass');await visit(page,'d-petra');
  await expect(page.getByRole('heading',{name:'Insert Disk E',exact:true})).toBeVisible();await capture(page,'disk-d-insert-e');
  const final=(await inspect(page)).state;expect(final.boundary).toBe('disk-e:brinewick-parcel');expect(final.flags.diskDComplete).toBe(true);
  for(const flag of ['dCrewReturned','dRelayStopped','dRecordRead','dHandBell','dEngineerRead','bEvacuated','bOrchardChannel','cTransferred','cWardHeat'])expect(final.flags[flag]).toBe(true);
  expect(final.gear).toEqual(departure.gear);expect(final.party.map(h=>h.id)).toEqual(['nell','orrin']);
  if(process.env.BT_QA_SAVE_OUTPUT)await writeFile(process.env.BT_QA_SAVE_OUTPUT,JSON.stringify(final,null,2));
  await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Insert Disk E',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Return to the line',exact:true}).click();
  await travel(page,'d-to-larkspur','station');await visit(page,'master');await visit(page,'b-family-larkspur');
  await travel(page,'c-stores-service','cinderbank');await travel(page,'c-to-infirmary','infirmary');await visit(page,'c-patients');
  expect((await inspect(page)).state.boundary).toBe(final.boundary);
  expect(errors).toEqual([]);expect(missing).toEqual([]);expect(await page.locator('vite-error-overlay').count()).toBe(0);
});

test('a phone can release both earths, close for the night, and keep the alternative outcome after reload',async({page})=>{
  test.setTimeout(180000);await page.setViewportSize({width:390,height:844});await page.goto('/');
  const state=enterDiskD(decodeSave(JSON.stringify(departure)));
  state.location={map:'northglass',x:14,y:17};await importSave(page,state);
  await expect.poll(async()=>(await inspect(page)).state.location.map).toBe('northglass');
  await approach(page,'d-petra');
  while(await page.locator('.dialogue').isVisible()){
    await expect(page.locator('.dialogue-actions button').first()).toBeInViewport();
    await expect(page.locator('.dialogue-portrait')).toBeInViewport();
    if((await page.locator('.dialogue h2').textContent())==='The letter')await capture(page,'disk-d-phone-letter');
    await page.locator('.dialogue-actions button').first().click();
  }
  Object.assign(state.flags,{dLetterRead:true,dLineHeld:true,dCrewReturned:true,dCircuitRead:true});
  state.location={map:'relayhall',x:31,y:25};state.party.forEach(h=>{h.hp=h.id==='nell'?66:78;});
  await importSave(page,state);await expect.poll(async()=>(await inspect(page)).state.location.map).toBe('relayhall');
  await approach(page,'d-plan');
  const plan=page.getByRole('button',{name:'Keep all signals red · close tonight',exact:true});
  while(!await plan.isVisible())await page.locator('.dialogue-actions button').first().click();
  await expect(plan).toBeInViewport();await expect(page.getByRole('button',{name:'Work by hand bell · keep local deliveries',exact:true})).toBeInViewport();
  await capture(page,'disk-d-phone-night-plan');await plan.click();
  await approach(page,'d-relay');await dialogue(page);await battle(page,'disk-d-phone-earths');
  await visit(page,'d-recorder');await travel(page,'d-to-yard','northglass');await visit(page,'d-petra');
  await expect(page.getByRole('heading',{name:'Insert Disk E',exact:true})).toBeVisible();await capture(page,'disk-d-phone-insert-e');
  await page.reload();await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Insert Disk E',exact:true})).toBeVisible();
  expect((await inspect(page)).state.flags.dHoldRed).toBe(true);expect((await inspect(page)).state.flags.dHandBell).toBeUndefined();
  await page.getByRole('button',{name:'Return to the line',exact:true}).click();await approach(page,'d-petra');
  await expect(page.locator('.dialogue')).toContainText('gone home on paid time');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
